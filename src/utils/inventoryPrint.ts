export type PrintColumn = {
  label: string;
  numeric?: boolean;
  code?: boolean;
  /** Excel number format for numeric cells. */
  format?: string;
};
export type PrintCellValue = string | number | null | undefined;
export type PrintCellMeta = {
  value?: PrintCellValue;
  raw?: number;
  formula?: string;
  format?: string;
};
/** Print text stays readable while Excel receives real numbers and formulas. */
export type PrintCell = PrintCellValue | PrintCellMeta;
export type PrintGroup = {
  title: string;
  detail?: string;
  rows: PrintCell[][];
  footer?: PrintCell[];
};
export type InventoryPrintReport = {
  printTracking?: { kind: string; id: number };
  title: string;
  context: string;
  columns: PrintColumn[];
  groups: PrintGroup[];
  footer?: PrintCell[];
  summary?: string;
  rowCount: number;
  excelSheetName?: string;
  excelWidths?: number[];
};
export type ReportPage<T> = {
  items: T[];
  total_items: number;
  total_pages: number;
};

/** Print every authorized filtered row, refusing truncated or changing pagination. */
export async function collectReportPages<
  T extends { id: number },
  P extends ReportPage<T> = ReportPage<T>,
>(fetchPage: (page: number) => Promise<P>) {
  const first = await fetchPage(1);
  if (
    !Array.isArray(first.items) ||
    !Number.isInteger(first.total_items) ||
    !Number.isInteger(first.total_pages) ||
    first.total_items < 0 ||
    first.total_pages < 0
  )
    throw new Error("Invalid report response");
  const items = [...first.items];
  for (let page = 2; page <= first.total_pages; page++) {
    const next = await fetchPage(page);
    if (!Array.isArray(next.items)) throw new Error("Invalid report response");
    if (
      next.total_items !== first.total_items ||
      next.total_pages !== first.total_pages
    )
      throw new Error("Data changed while preparing the report. Please retry.");
    items.push(...next.items);
  }
  if (
    items.length !== first.total_items ||
    new Set(items.map((row) => row.id)).size !== items.length
  )
    throw new Error("The complete report could not be loaded. Please retry.");
  return { ...first, items };
}

export const printNumber = (value: unknown) =>
  Number(value ?? 0).toLocaleString("id-ID", { maximumFractionDigits: 4 });
export const printMoney = (value: unknown) =>
  "Rp " +
  Number(value ?? 0).toLocaleString("id-ID", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });

/** Attach a raw numeric value to printed text for one-sheet Excel exports. */
export const printCell = (
  value: PrintCellValue,
  raw?: number,
  format?: string,
): PrintCell => {
  const numeric = Number(raw);
  return raw != null && Number.isFinite(numeric)
    ? { value, raw: numeric, format }
    : value;
};

const escape = (value: unknown) =>
  String(value ?? "—").replace(
    /[&<>"']/g,
    (ch) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        ch
      ]!,
  );

const columnName = (index: number) => {
  let value = index + 1;
  let name = "";
  while (value > 0) {
    const remainder = (value - 1) % 26;
    name = String.fromCharCode(65 + remainder) + name;
    value = Math.floor((value - 1) / 26);
  }
  return name;
};

const asMeta = (cell: PrintCell): PrintCellMeta =>
  cell && typeof cell === "object" && !Array.isArray(cell)
    ? cell
    : { value: cell as PrintCellValue };

const safeSheetName = (value: string) =>
  value.replace(/[\\/?*[\]:]/g, " ").trim().slice(0, 31) || "Sheet";

export function renderInventoryPrint(
  report: InventoryPrintReport,
  generatedBy: string,
  generatedAt = new Date(),
) {
  const timestamp = generatedAt.toLocaleString("id-ID", {
    timeZone: "Asia/Jakarta",
  });
  const generatedIso = generatedAt.toISOString();
  const cellCount = Math.max(1, report.columns.length);
  const lastColumn = columnName(cellCount - 1);
  const metaRows: Array<[string, PrintCellValue]> = [
    ["REPORT", report.title],
    ["CONTEXT", report.context],
    ["GENERATED AT", `${timestamp} WIB`],
    ["GENERATED ISO", generatedIso],
    ["GENERATED BY", generatedBy],
    ["RECORDS", report.rowCount],
    ...(report.summary ? ([["SUMMARY", report.summary]] as Array<[string, PrintCellValue]>) : []),
  ];
  // The visible print header is row 1. Excel gets an additional hidden header
  // directly below the metadata so AutoFilter and frozen panes start on the
  // real field names instead of the audit metadata.
  const exportHeaderRow = metaRows.length + 2;

  const cells = (row: PrintCell[], tag = "td") =>
    report.columns
      .map((col, i) => {
        const meta = asMeta(row[i]);
        const raw = meta.raw != null ? Number(meta.raw) : NaN;
        const hasRaw = Number.isFinite(raw);
        const format = meta.format || col.format || (col.numeric ? "#,##0.00" : "");
        const attributes = [
          hasRaw ? ` data-v="${raw}" data-t="n"` : "",
          hasRaw && format ? ` data-z="${escape(format)}"` : "",
          meta.formula ? ` data-f="${escape(meta.formula)}"` : "",
        ]
          .filter(Boolean)
          .join("");
        return `<${tag} class="${col.numeric ? "numeric" : ""} ${col.code ? "code" : ""}"${attributes}>${escape(
          meta.value !== undefined ? meta.value : hasRaw ? raw : "—",
        )}</${tag}>`;
      })
      .join("");

  const sumRef = (columnIndex: number, rows: number[]) => {
    if (!rows.length) return "";
    const col = columnName(columnIndex);
    if (rows[rows.length - 1] - rows[0] === rows.length - 1) {
      return `${col}${rows[0]}:${col}${rows[rows.length - 1]}`;
    }
    return rows.map((row) => `${col}${row}`).join(",");
  };
  const withSum = (cell: PrintCell, columnIndex: number, rows: number[]): PrintCell => {
    const meta = asMeta(cell);
    if (meta.raw == null || meta.formula || !report.columns[columnIndex]?.numeric || !rows.length) {
      return cell;
    }
    const refs = sumRef(columnIndex, rows);
    return refs ? { ...meta, formula: `SUM(${refs})` } : cell;
  };
  const sequential = (start: number, end: number) =>
    end >= start ? Array.from({ length: end - start + 1 }, (_, i) => start + i) : [];

  const body: string[] = [];
  const detailRows: number[] = [];
  const groupFooterRows: number[] = [];
  let cursor = exportHeaderRow + 1;
  for (const group of report.groups) {
    body.push(
      `<tr class="group"><td colspan="${cellCount}">${escape(group.title)}${
        group.detail ? `<div class="detail">${escape(group.detail)}</div>` : ""
      }</td></tr>`,
    );
    cursor += 1;
    const start = cursor;
    for (const row of group.rows) {
      body.push(`<tr>${cells(row)}</tr>`);
      detailRows.push(cursor);
      cursor += 1;
    }
    const end = cursor - 1;
    if (group.footer) {
      const footer = group.footer.map((cell, i) => withSum(cell, i, sequential(start, end)));
      body.push(`<tr class="subtotal">${cells(footer)}</tr>`);
      groupFooterRows.push(cursor);
      cursor += 1;
    }
  }
  if (!report.groups.length) {
    body.push(`<tr><td class="empty" colspan="${cellCount}">No records match the selected filters.</td></tr>`);
    cursor += 1;
  }
  const detailLastRow = cursor - 1;
  if (report.footer) {
    const footer = report.footer.map((cell, i) =>
      withSum(cell, i, groupFooterRows.length ? groupFooterRows : detailRows),
    );
    body.push(`<tr class="grand">${cells(footer)}</tr>`);
    cursor += 1;
  }
  body.push(`<tr style="display:none"><td>EXPORT SOURCE</td><td>MMH-Connect inventory report</td></tr>`);
  body.push(`<tr style="display:none"><td>GENERATED ISO</td><td>${escape(generatedIso)}</td></tr>`);

  const widths = report.excelWidths?.length
    ? report.excelWidths
    : report.columns.map((col) => (col.code ? 18 : col.numeric ? 18 : 30));
  const tableAttributes = [
    `data-export-sheet="${escape(safeSheetName(report.excelSheetName || report.title))}"`,
    `data-export-widths="${escape(widths.join(","))}"`,
    `data-export-autofilter-range="A${exportHeaderRow}:${lastColumn}${Math.max(exportHeaderRow, detailLastRow)}"`,
    `data-export-freeze-row="${exportHeaderRow}"`,
  ].join(" ");
  const fontBase = typeof window !== "undefined" ? window.location.origin : "";

  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>${escape(report.title)}</title><style>
    @font-face { font-family: Roboto; font-weight: 100 900; font-style: normal; font-display: swap; src: url("${fontBase}/fonts/roboto-latin-wght-normal.woff2") format("woff2"); }
    @page { size: A4 landscape; margin: 12mm 10mm 15mm; @bottom-left { content: "MMH-Connect"; font: 8pt Roboto, Arial, sans-serif; color: #555; } @bottom-right { content: "Page " counter(page) " / " counter(pages); font: 8pt Roboto, Arial, sans-serif; color: #555; } }
    * { box-sizing: border-box; } body { margin: 0; color: #17211b; font: 9pt Roboto, Arial, sans-serif; }
    .company { font-size: 9pt; font-weight: bold; } h1 { margin: 3mm 0 2mm; font-size: 15pt; } .meta { font-size: 8pt; line-height: 1.5; } .summary { margin-top: 3mm; font-weight: bold; }
    table { width: 100%; border-collapse: collapse; margin-top: 4mm; font-size: 8.5pt; } thead { display: table-header-group; } th { background: #edf1ee; border-top: 1px solid #7b887e; border-bottom: 1px solid #7b887e; text-align: left; } th, td { padding: 1.6mm 1.2mm; vertical-align: top; } td { border-bottom: 1px solid #e1e5e2; } .numeric { text-align: right; white-space: nowrap; font-variant-numeric: tabular-nums; } .code { font-weight: bold; white-space: nowrap; } tr { break-inside: avoid; } .group td { padding-top: 3mm; background: #f4f6f4; font-weight: bold; } .group { break-after: avoid; } .detail { font-weight: normal; font-size: 8pt; } .subtotal td { border-top: 1px solid #a8b2aa; font-weight: bold; } .grand td { border-top: 2px solid #56645a; font-weight: bold; } .empty { padding: 8mm; text-align: center; } th, .group td { print-color-adjust: exact; -webkit-print-color-adjust: exact; }
    @media screen { body { padding: 16px; background: white; } }
  </style></head><body><div class="company">MMH-Connect</div><h1>${escape(report.title)}</h1><div class="meta">${escape(
    report.context,
  )}<br>Generated: ${escape(timestamp)} WIB · By: ${escape(generatedBy)} · Records: ${report.rowCount}</div>${
    report.summary ? `<div class="summary">${escape(report.summary)}</div>` : ""
  }<table ${tableAttributes}><thead><tr>${cells(
    report.columns.map((column) => column.label),
    "th",
  )}</tr></thead><tbody>${metaRows
    .map(
      ([label, value]) =>
        `<tr style="display:none"><td>${escape(label)}</td><td>${escape(value)}</td></tr>`,
    )
    .join("")}<tr style="display:none">${cells(
      report.columns.map((column) => column.label),
      "th",
    )}</tr>${body.join("")}</tbody></table></body></html>`;
}
