import type { ReactNode } from "react";

type Column<Row> = {
  label: string;
  align?: "left" | "center" | "right";
  render: (row: Row, index: number) => ReactNode;
};

type SummaryItem = { label: string; value: ReactNode };

type Props<Row> = {
  title: string;
  subtitle?: ReactNode;
  filters?: SummaryItem[];
  columns: Column<Row>[];
  rows: Row[];
  rowKey?: (row: Row, index: number) => string | number;
  footerRows?: ReactNode;
  control?: ReactNode;
  printedBy?: ReactNode;
  generatedAt?: string | null;
  orientation?: "portrait" | "landscape";
};

const align = {
  left: "text-left",
  center: "text-center",
  right: "text-right",
} as const;

export default function FinancialReportPrintTemplate<Row>({
  title,
  subtitle,
  filters = [],
  columns,
  rows,
  rowKey,
  footerRows,
  control,
  printedBy,
  generatedAt,
  orientation = "landscape",
}: Props<Row>) {
  return (
    <article className="finance-report print-document mx-auto bg-white p-6 text-[10px] leading-tight text-slate-950 print:p-0">
      <style>{`
        @page { size: A4 ${orientation}; margin: 10mm 10mm 12mm 10mm; }
        @media print {
          body { background: #fff !important; }
          .finance-report thead { display: table-header-group; }
          .finance-report tfoot { display: table-row-group; }
          .finance-report th { color: #111; }
          .finance-report td { font-variant-numeric: tabular-nums; }
          .finance-report { font-family: Arial, sans-serif; }
          .finance-report-header + table { table-layout: auto; }
          .finance-report tr { break-inside: avoid; page-break-inside: avoid; }
          .finance-report-header { break-inside: avoid; page-break-inside: avoid; }
        }
      `}</style>

      <header className="finance-report-header mb-4 border-b-2 border-slate-800 pb-3">
        <div className="grid grid-cols-[90px_1fr_90px] items-center">
          <img src="/logoprint.jpeg" alt="PT. Mutiara Merdeka Hotel" className="h-12 w-auto object-contain" />
          <div className="text-center">
            <div className="text-base font-bold tracking-wide">PT. MUTIARA MERDEKA HOTEL</div>
            <h1 className="mt-0.5 text-lg font-bold tracking-wide">{title.toUpperCase()}</h1>
            {subtitle ? <div className="mt-1 text-[10px]">{subtitle}</div> : null}
          </div>
          <div />
        </div>
        {filters.length ? (
          <div className="mt-3 grid grid-cols-3 gap-x-8 gap-y-1">
            {filters.map((item, index) => (
              <div key={index}>
                <span className="font-semibold">{item.label}: </span>
                <span>{item.value ?? "—"}</span>
              </div>
            ))}
          </div>
        ) : null}
      </header>

      <table className="w-full border-collapse">
        <thead>
          <tr>
            {columns.map((column, index) => (
              <th
                key={index}
                className={`border border-slate-700 px-1.5 py-1 font-semibold ${align[column.align ?? "left"]}`}
              >
                {column.label}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((row, index) => (
            <tr key={rowKey ? rowKey(row, index) : index}>
              {columns.map((column, columnIndex) => (
                <td
                  key={columnIndex}
                  className={`border border-slate-400 px-1.5 py-1 align-top ${align[column.align ?? "left"]}`}
                >
                  {column.render(row, index)}
                </td>
              ))}
            </tr>
          ))}
          {!rows.length ? (
            <tr>
              <td colSpan={columns.length} className="border border-slate-400 px-2 py-5 text-center text-slate-500">
                No data for the selected filters.
              </td>
            </tr>
          ) : null}
        </tbody>
        {footerRows ? <tfoot>{footerRows}</tfoot> : null}
      </table>

      {control ? <section className="mt-4 border-t-2 border-slate-800 pt-2">{control}</section> : null}

      <footer className="mt-4 flex justify-between border-t border-slate-300 pt-2 text-[9px] text-slate-600">
        <span>Generated by MMH-Connect{printedBy ? <> · Printed by {printedBy}</> : null}</span>
        <span>{generatedAt ? new Date(generatedAt).toLocaleString("id-ID") : new Date().toLocaleString("id-ID")}</span>
      </footer>
    </article>
  );
}
