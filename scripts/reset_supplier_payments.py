#!/usr/bin/env python3
"""Remove all supplier Payment test data and restore supplier invoice/AP balances.

This maintenance script is intentionally scoped to supplier payments only:
- deletes General Ledger rows created by SUPPLIER_PAYMENT journals
- deletes SUPPLIER_PAYMENT journals (including DRAFT/VOID/POSTED)
- clears Payment Voucher -> Payment links
- deletes all Payment records (allocations/funding cascade)
- recomputes SupplierInvoice paid/balance/payment_status from zero posted payments
- synchronizes AccountPayable mirrors

It does NOT touch supplier invoices, goods receipts, invoice journals, historical
PPN-repair journals, payment vouchers themselves, or customer payments.

Dry-run by default. Pass --apply to commit.
"""
from __future__ import annotations

import argparse
import os
import sys
from decimal import Decimal
from pathlib import Path

os.environ.setdefault("SECRET_KEY", "supplier-payment-reset-local-0123456789abcdef")
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.core.database import SessionLocal
from app.models.account_payable import AccountPayable
from app.models.general_ledger import GeneralLedger
from app.models.journal_entry import JournalEntry
from app.models.payment import Payment
from app.models.payment_voucher import PaymentVoucher
from app.models.supplier_invoice import SupplierInvoice

ZERO = Decimal("0")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()

    db = SessionLocal()
    try:
        payments = db.query(Payment).order_by(Payment.id).all()
        payment_ids = [p.id for p in payments]
        payment_numbers = [p.payment_number for p in payments]

        journals = (
            db.query(JournalEntry)
            .filter(JournalEntry.reference_type == "SUPPLIER_PAYMENT")
            .order_by(JournalEntry.id)
            .all()
        )
        journal_ids = [j.id for j in journals]
        journal_numbers = [j.journal_number for j in journals]

        gl_query = db.query(GeneralLedger).filter(
            GeneralLedger.reference_type == "SUPPLIER_PAYMENT"
        )
        gl_count = gl_query.count()

        linked_vouchers = (
            db.query(PaymentVoucher)
            .filter(PaymentVoucher.payment_id.isnot(None))
            .all()
        )

        affected_invoice_ids = {
            allocation.supplier_invoice_id
            for payment in payments
            for allocation in payment.allocations
        }

        print("MODE:", "APPLY" if args.apply else "DRY RUN")
        print("payments:", len(payments), payment_numbers)
        print("payment_journals:", len(journals), journal_numbers)
        print("general_ledger_rows:", gl_count)
        print("linked_payment_vouchers:", len(linked_vouchers))
        print("affected_supplier_invoices:", len(affected_invoice_ids))

        if not args.apply:
            db.rollback()
            print("RESULT: DRY RUN ONLY")
            return

        # Break direct FK references before deleting journals/payments.
        for voucher in linked_vouchers:
            voucher.payment_id = None

        for payment in payments:
            payment.journal_entry_id = None

        db.flush()

        # Remove GL postings generated by supplier payment journals.
        gl_query.delete(synchronize_session=False)

        # Remove all payment journals, including old VOID drafts created by reopen.
        if journal_ids:
            (
                db.query(JournalEntry)
                .filter(JournalEntry.id.in_(journal_ids))
                .delete(synchronize_session=False)
            )

        # Delete payments; allocations and funding lines cascade from Payment.
        if payment_ids:
            (
                db.query(Payment)
                .filter(Payment.id.in_(payment_ids))
                .delete(synchronize_session=False)
            )

        db.flush()

        # All supplier payments are now gone, so invoice payment state is zero.
        invoices = db.query(SupplierInvoice).all()
        for invoice in invoices:
            total = Decimal(invoice.total_amount or 0)
            adjustments = Decimal(invoice.adjustment_amount or 0)
            balance = max(ZERO, total - adjustments)

            invoice.paid_amount = ZERO
            invoice.balance_amount = balance
            invoice.payment_status = (
                "PAID" if balance == ZERO and total > ZERO
                else "PARTIALLY_PAID" if adjustments > ZERO
                else "UNPAID"
            )

            payable = (
                db.query(AccountPayable)
                .filter(
                    AccountPayable.supplier_id == invoice.supplier_id,
                    AccountPayable.invoice_number == invoice.internal_invoice_number,
                )
                .first()
            )
            if payable:
                payable.amount = total
                payable.paid_amount = ZERO
                payable.outstanding_amount = balance
                payable.payment_status = invoice.payment_status
                payable.status = "PAID" if balance == ZERO else "OPEN"
                payable.last_payment_date = None

        db.commit()

        print("RESULT: APPLIED")
        print("remaining_payments:", db.query(Payment).count())
        print(
            "remaining_supplier_payment_journals:",
            db.query(JournalEntry)
            .filter(JournalEntry.reference_type == "SUPPLIER_PAYMENT")
            .count(),
        )
        print(
            "remaining_supplier_payment_gl:",
            db.query(GeneralLedger)
            .filter(GeneralLedger.reference_type == "SUPPLIER_PAYMENT")
            .count(),
        )
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


if __name__ == "__main__":
    main()
