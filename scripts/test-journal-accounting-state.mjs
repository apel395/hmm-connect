import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const bundle = await build({ entryPoints: ['src/modules/finance/journals/journalState.ts'], bundle: true, write: false, platform: 'node', format: 'cjs' });
const module = { exports: {} };
new Function('module', 'exports', 'require', bundle.outputFiles[0].text)(module, module.exports, require);
const { journalAccountingLabel, journalAllowsBulk } = module.exports;
const draft = { status: 'DRAFT', period_locked: false, accounting_recognized: true, allowed_actions: { can_post: true, can_unpost: false } };
assert.equal(journalAccountingLabel(draft), 'Recognized');
assert.equal(journalAllowsBulk(draft, 'post'), true);
assert.equal(journalAllowsBulk(draft, 'unpost'), false);
assert.equal(journalAccountingLabel({ ...draft, accounting_recognized: false }), 'Not recognized');
const locked = { ...draft, status: 'POSTED', period_locked: true, allowed_actions: { can_post: true, can_unpost: true } };
assert.equal(journalAccountingLabel(locked), 'Locked');
assert.equal(journalAllowsBulk(locked, 'post'), false);
assert.equal(journalAllowsBulk(locked, 'unpost'), false);
const reopened = { ...locked, period_locked: false };
assert.equal(journalAllowsBulk(reopened, 'unpost'), true);
assert.equal(journalAllowsBulk({ ...reopened, allowed_actions: { can_unpost: false } }, 'unpost'), false);
assert.equal(journalAllowsBulk({ ...draft, status: 'VOID' }, 'post'), false);
console.log('Journal accounting state PASS: recognized drafts, locked periods, reopened posted journals and server-authorized bulk actions.');
