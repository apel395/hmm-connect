from datetime import date, datetime
from decimal import Decimal
from sqlalchemy import Boolean, CheckConstraint, Date, DateTime, ForeignKey, Integer, Numeric, String, Text, UniqueConstraint, func
from sqlalchemy.orm import Mapped, mapped_column, relationship
from app.models.base import Base

class FixedAssetCategory(Base):
    __tablename__ = "fixed_asset_categories"
    id: Mapped[int] = mapped_column(primary_key=True)
    code: Mapped[str] = mapped_column(String(30), unique=True, index=True)
    name: Mapped[str] = mapped_column(String(120))
    default_useful_life_months: Mapped[int] = mapped_column(Integer)
    default_residual_percentage: Mapped[Decimal] = mapped_column(Numeric(7, 4), default=0)
    asset_account_id: Mapped[int] = mapped_column(ForeignKey("chart_of_accounts.id"))
    accumulated_depreciation_account_id: Mapped[int] = mapped_column(ForeignKey("chart_of_accounts.id"))
    depreciation_expense_account_id: Mapped[int] = mapped_column(ForeignKey("chart_of_accounts.id"))
    disposal_gain_account_id: Mapped[int | None] = mapped_column(ForeignKey("chart_of_accounts.id"))
    disposal_loss_account_id: Mapped[int | None] = mapped_column(ForeignKey("chart_of_accounts.id"))
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)
    description: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), onupdate=func.now())

class FixedAsset(Base):
    __tablename__ = "fixed_assets"
    __table_args__ = (CheckConstraint("status = 'PENDING_REGISTRATION' OR (acquisition_date IS NOT NULL AND acquisition_cost IS NOT NULL AND business_unit_id IS NOT NULL AND created_by_id IS NOT NULL)", name="ck_fixed_asset_registered_details"),)
    id: Mapped[int] = mapped_column(primary_key=True)
    asset_number: Mapped[str] = mapped_column(String(50), unique=True, index=True)
    asset_name: Mapped[str] = mapped_column(String(180), index=True)
    asset_category_id: Mapped[int | None] = mapped_column(ForeignKey("fixed_asset_categories.id"), nullable=True, index=True)
    description: Mapped[str | None] = mapped_column(Text)
    serial_number: Mapped[str | None] = mapped_column(String(100))
    barcode: Mapped[str | None] = mapped_column(String(100), unique=True)
    acquisition_date: Mapped[date | None] = mapped_column(Date, nullable=True, index=True)
    capitalization_date: Mapped[date | None] = mapped_column(Date)
    acquisition_cost: Mapped[Decimal | None] = mapped_column(Numeric(18, 2), nullable=True)
    residual_value: Mapped[Decimal] = mapped_column(Numeric(18, 2), default=0)
    useful_life_months: Mapped[int | None] = mapped_column(Integer, nullable=True)
    depreciation_method: Mapped[str] = mapped_column(String(30), default="STRAIGHT_LINE")
    depreciation_start_date: Mapped[date | None] = mapped_column(Date)
    accumulated_depreciation: Mapped[Decimal] = mapped_column(Numeric(18, 2), default=0)
    net_book_value: Mapped[Decimal | None] = mapped_column(Numeric(18, 2), nullable=True, default=0)
    status: Mapped[str] = mapped_column(String(30), default="DRAFT", index=True)
    business_unit_id: Mapped[int | None] = mapped_column(ForeignKey("business_units.id"), nullable=True, index=True)
    location_id: Mapped[int | None] = mapped_column(ForeignKey("locations.id"), index=True)
    department_id: Mapped[int | None] = mapped_column(ForeignKey("departments.id"), index=True)
    custodian_user_id: Mapped[int | None] = mapped_column(ForeignKey("users.id"))
    supplier_id: Mapped[int | None] = mapped_column(ForeignKey("suppliers.id"))
    purchase_invoice_id: Mapped[int | None] = mapped_column(ForeignKey("supplier_invoices.id"), index=True)
    product_id: Mapped[int | None] = mapped_column(ForeignKey("products.id"), nullable=True, index=True)
    product = relationship("Product")
    source_invoice_line_id: Mapped[int | None] = mapped_column(ForeignKey("supplier_invoice_lines.id"), unique=True, nullable=True, index=True)
    purchase_order_id: Mapped[int | None] = mapped_column(ForeignKey("purchase_orders.id"))
    goods_receipt_id: Mapped[int | None] = mapped_column(ForeignKey("goods_receipts.id"))
    asset_account_id: Mapped[int] = mapped_column(ForeignKey("chart_of_accounts.id"))
    accumulated_depreciation_account_id: Mapped[int | None] = mapped_column(ForeignKey("chart_of_accounts.id"), nullable=True)
    depreciation_expense_account_id: Mapped[int | None] = mapped_column(ForeignKey("chart_of_accounts.id"), nullable=True)
    disposal_gain_account_id: Mapped[int | None] = mapped_column(ForeignKey("chart_of_accounts.id"))
    disposal_loss_account_id: Mapped[int | None] = mapped_column(ForeignKey("chart_of_accounts.id"))
    source_type: Mapped[str] = mapped_column(String(30), default="MANUAL")
    external_reference: Mapped[str | None] = mapped_column(String(120))
    notes: Mapped[str | None] = mapped_column(Text)
    created_by_id: Mapped[int | None] = mapped_column(ForeignKey("users.id"), nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), onupdate=func.now())
    disposed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    written_off_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    category = relationship("FixedAssetCategory")
    schedules = relationship("FixedAssetDepreciationSchedule", back_populates="asset", cascade="all, delete-orphan")
    movements = relationship("FixedAssetMovement", back_populates="asset", cascade="all, delete-orphan")

class FixedAssetDepreciationSchedule(Base):
    __tablename__ = "fixed_asset_depreciation_schedules"
    __table_args__ = (UniqueConstraint("fixed_asset_id", "period_year", "period_month", name="uq_asset_depreciation_period"),)
    id: Mapped[int] = mapped_column(primary_key=True)
    fixed_asset_id: Mapped[int] = mapped_column(ForeignKey("fixed_assets.id", ondelete="CASCADE"), index=True)
    period_year: Mapped[int] = mapped_column(Integer, index=True)
    period_month: Mapped[int] = mapped_column(Integer, index=True)
    period_start: Mapped[date] = mapped_column(Date)
    period_end: Mapped[date] = mapped_column(Date)
    opening_book_value: Mapped[Decimal] = mapped_column(Numeric(18, 2))
    depreciation_amount: Mapped[Decimal] = mapped_column(Numeric(18, 2))
    accumulated_depreciation: Mapped[Decimal] = mapped_column(Numeric(18, 2))
    closing_book_value: Mapped[Decimal] = mapped_column(Numeric(18, 2))
    status: Mapped[str] = mapped_column(String(20), default="PLANNED", index=True)
    journal_entry_id: Mapped[int | None] = mapped_column(ForeignKey("journal_entries.id"))
    generated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    posted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    asset = relationship("FixedAsset", back_populates="schedules")

class FixedAssetMovement(Base):
    __tablename__ = "fixed_asset_movements"
    id: Mapped[int] = mapped_column(primary_key=True)
    fixed_asset_id: Mapped[int] = mapped_column(ForeignKey("fixed_assets.id", ondelete="CASCADE"), index=True)
    movement_type: Mapped[str] = mapped_column(String(30), index=True)
    from_business_unit_id: Mapped[int | None] = mapped_column(ForeignKey("business_units.id"))
    to_business_unit_id: Mapped[int | None] = mapped_column(ForeignKey("business_units.id"))
    from_location_id: Mapped[int | None] = mapped_column(ForeignKey("locations.id"))
    to_location_id: Mapped[int | None] = mapped_column(ForeignKey("locations.id"))
    from_department_id: Mapped[int | None] = mapped_column(ForeignKey("departments.id"))
    to_department_id: Mapped[int | None] = mapped_column(ForeignKey("departments.id"))
    movement_date: Mapped[date] = mapped_column(Date)
    reference_number: Mapped[str | None] = mapped_column(String(100))
    notes: Mapped[str | None] = mapped_column(Text)
    created_by_id: Mapped[int] = mapped_column(ForeignKey("users.id"))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    asset = relationship("FixedAsset", back_populates="movements")

class FixedAssetDepreciationRun(Base):
    __tablename__ = "fixed_asset_depreciation_runs"
    __table_args__ = (UniqueConstraint("period_year", "period_month", "business_unit_id", "location_id", name="uq_asset_run_scope"),)
    id: Mapped[int] = mapped_column(primary_key=True)
    run_number: Mapped[str] = mapped_column(String(50), unique=True, index=True)
    period_year: Mapped[int] = mapped_column(Integer)
    period_month: Mapped[int] = mapped_column(Integer)
    business_unit_id: Mapped[int | None] = mapped_column(ForeignKey("business_units.id"), index=True)
    location_id: Mapped[int | None] = mapped_column(ForeignKey("locations.id"), index=True)
    status: Mapped[str] = mapped_column(String(20), default="DRAFT", index=True)
    asset_count: Mapped[int] = mapped_column(Integer, default=0)
    total_depreciation: Mapped[Decimal] = mapped_column(Numeric(18, 2), default=0)
    journal_entry_id: Mapped[int | None] = mapped_column(ForeignKey("journal_entries.id"))
    notes: Mapped[str | None] = mapped_column(Text)
    created_by_id: Mapped[int] = mapped_column(ForeignKey("users.id"))
    posted_by_id: Mapped[int | None] = mapped_column(ForeignKey("users.id"))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    posted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
