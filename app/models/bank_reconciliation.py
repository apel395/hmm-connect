from datetime import date, datetime
from decimal import Decimal
from sqlalchemy import Date, DateTime, ForeignKey, JSON, Numeric, String, Text, func
from sqlalchemy.orm import Mapped, mapped_column, relationship
from app.models.base import Base

class BankReconciliation(Base):
    __tablename__="bank_reconciliations"
    id:Mapped[int]=mapped_column(primary_key=True)
    reconciliation_number:Mapped[str]=mapped_column(String(50),unique=True,index=True)
    account_id:Mapped[int]=mapped_column(ForeignKey("chart_of_accounts.id"),index=True)
    business_unit_id:Mapped[int|None]=mapped_column(ForeignKey("business_units.id",ondelete="SET NULL"),index=True)
    location_id:Mapped[int|None]=mapped_column(ForeignKey("locations.id",ondelete="SET NULL"),index=True)
    department_id:Mapped[int|None]=mapped_column(ForeignKey("departments.id",ondelete="SET NULL"),index=True)
    statement_start_date:Mapped[date]=mapped_column(Date,index=True)
    statement_end_date:Mapped[date]=mapped_column(Date,index=True)
    statement_opening_balance:Mapped[Decimal]=mapped_column(Numeric(18,2))
    statement_closing_balance:Mapped[Decimal]=mapped_column(Numeric(18,2))
    system_opening_balance:Mapped[Decimal]=mapped_column(Numeric(18,2),default=0)
    system_closing_balance:Mapped[Decimal]=mapped_column(Numeric(18,2),default=0)
    total_statement_debit:Mapped[Decimal]=mapped_column(Numeric(18,2),default=0)
    total_statement_credit:Mapped[Decimal]=mapped_column(Numeric(18,2),default=0)
    total_system_debit:Mapped[Decimal]=mapped_column(Numeric(18,2),default=0)
    total_system_credit:Mapped[Decimal]=mapped_column(Numeric(18,2),default=0)
    matched_amount:Mapped[Decimal]=mapped_column(Numeric(18,2),default=0)
    unmatched_statement_amount:Mapped[Decimal]=mapped_column(Numeric(18,2),default=0)
    unmatched_system_amount:Mapped[Decimal]=mapped_column(Numeric(18,2),default=0)
    adjustment_amount:Mapped[Decimal]=mapped_column(Numeric(18,2),default=0)
    difference:Mapped[Decimal]=mapped_column(Numeric(18,2),default=0)
    status:Mapped[str]=mapped_column(String(20),default="DRAFT",index=True)
    notes:Mapped[str|None]=mapped_column(Text)
    source_filename:Mapped[str|None]=mapped_column(String(255))
    created_by_id:Mapped[int|None]=mapped_column(ForeignKey("users.id"))
    completed_by_id:Mapped[int|None]=mapped_column(ForeignKey("users.id"))
    created_at:Mapped[datetime]=mapped_column(DateTime(timezone=True),server_default=func.now())
    updated_at:Mapped[datetime]=mapped_column(DateTime(timezone=True),server_default=func.now(),onupdate=func.now())
    completed_at:Mapped[datetime|None]=mapped_column(DateTime(timezone=True))
    voided_at:Mapped[datetime|None]=mapped_column(DateTime(timezone=True))
    account=relationship("ChartOfAccount")
    created_by=relationship("User",foreign_keys=[created_by_id])
    completed_by=relationship("User",foreign_keys=[completed_by_id])
    statement_lines=relationship("BankStatementLine",back_populates="reconciliation",cascade="all, delete-orphan")
    matches=relationship("BankReconciliationMatch",back_populates="reconciliation",cascade="all, delete-orphan")

class BankStatementLine(Base):
    __tablename__="bank_statement_lines"
    id:Mapped[int]=mapped_column(primary_key=True)
    reconciliation_id:Mapped[int]=mapped_column(ForeignKey("bank_reconciliations.id",ondelete="CASCADE"),index=True)
    transaction_date:Mapped[date]=mapped_column(Date,index=True)
    value_date:Mapped[date|None]=mapped_column(Date)
    description:Mapped[str|None]=mapped_column(Text)
    reference_number:Mapped[str|None]=mapped_column(String(150),index=True)
    debit:Mapped[Decimal]=mapped_column(Numeric(18,2),default=0)
    credit:Mapped[Decimal]=mapped_column(Numeric(18,2),default=0)
    balance:Mapped[Decimal|None]=mapped_column(Numeric(18,2))
    external_transaction_id:Mapped[str|None]=mapped_column(String(150),index=True)
    counterparty_name:Mapped[str|None]=mapped_column(String(255))
    raw_data_json:Mapped[dict|None]=mapped_column(JSON)
    match_status:Mapped[str]=mapped_column(String(25),default="UNMATCHED",index=True)
    matched_journal_line_id:Mapped[int|None]=mapped_column(ForeignKey("journal_lines.id"),index=True)
    matched_at:Mapped[datetime|None]=mapped_column(DateTime(timezone=True))
    reconciliation=relationship("BankReconciliation",back_populates="statement_lines")
    matches=relationship("BankReconciliationMatch",back_populates="statement_line",cascade="all, delete-orphan")

class BankReconciliationMatch(Base):
    __tablename__="bank_reconciliation_matches"
    id:Mapped[int]=mapped_column(primary_key=True)
    reconciliation_id:Mapped[int]=mapped_column(ForeignKey("bank_reconciliations.id",ondelete="CASCADE"),index=True)
    statement_line_id:Mapped[int]=mapped_column(ForeignKey("bank_statement_lines.id",ondelete="CASCADE"),index=True)
    journal_line_id:Mapped[int]=mapped_column(ForeignKey("journal_lines.id"),index=True)
    matched_amount:Mapped[Decimal]=mapped_column(Numeric(18,2))
    match_type:Mapped[str]=mapped_column(String(20))
    confidence_score:Mapped[Decimal|None]=mapped_column(Numeric(5,2))
    matched_by_id:Mapped[int|None]=mapped_column(ForeignKey("users.id"))
    created_at:Mapped[datetime]=mapped_column(DateTime(timezone=True),server_default=func.now())
    reconciliation=relationship("BankReconciliation",back_populates="matches")
    statement_line=relationship("BankStatementLine",back_populates="matches")
    journal_line=relationship("JournalLine")
    matched_by=relationship("User")
